        function renderQuestion() {

            let item = questions[index];

            // اینجا جواب‌ها رندوم می‌شن
            const shuffledAnswers = shuffle(item.a);

            area.innerHTML = `

            <div class="progress-box">

                <p>
                💀 مرحله ${index + 1} از ${questions.length}
                </p>

                <div class="bar">
                    <span style="width:${((index) / questions.length) * 100}%"></span>
                </div>

            </div>



            <div class="question">
                ${item.q}
            </div>



            <div>
            ${
                shuffledAnswers.map((a, i) => `
                <button class="secondary answer" data-id="${i}">
                    ${String.fromCharCode(65 + i)} - ${a[0]}
                </button>
                `).join("")
            }
            </div>

            `;



            document.querySelectorAll(".answer").forEach(btn => {

                btn.onclick = () => {

                    // چون جواب‌ها شافل شدن، باید از shuffledAnswers بخونیم
                    let answer = shuffledAnswers[Number(btn.dataset.id)];
                    scores[answer[1]]++;

                    index++;

                    if (index >= questions.length) {
                        finish();
                    } else {
                        area.style.opacity = "0";
                        area.style.transform = "translateY(8px)";

                        setTimeout(() => {
                            area.style.opacity = "1";
                            area.style.transform = "translateY(0)";
                            renderQuestion();
                        }, 280);
                    }
                };
            });
        }




